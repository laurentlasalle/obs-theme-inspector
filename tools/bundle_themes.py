#!/usr/bin/env python3
"""Bundles OBS's own theme files and UI images into a JavaScript file.

Browsers do not let a page opened from disk (file://) read the files next to
it, so the default themes are embedded in app/bundle-obs-<version>.js.

Usage:
    python3 tools/bundle_themes.py 32.2.1

Expects:
    themes/obs-<version>/            content of frontend/data/themes
    resources/obs-<version>-images/  content of frontend/forms/images

SPDX-License-Identifier: GPL-2.0-or-later
"""
import base64
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TEXT_EXT = {".obt", ".ovt", ".oha", ".svg"}
IMAGE_EXT = {".svg", ".png"}


def collect(folder, extensions):
    files = {}
    for path in sorted(folder.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in extensions:
            continue
        rel = path.relative_to(folder).as_posix()
        if path.suffix.lower() in TEXT_EXT:
            files[rel] = path.read_text(encoding="utf-8")
        else:
            files[rel] = "base64:" + base64.b64encode(path.read_bytes()).decode("ascii")
    return files


def main():
    version = sys.argv[1] if len(sys.argv) > 1 else "32.2.1"
    themes = collect(ROOT / "themes" / f"obs-{version}", TEXT_EXT | IMAGE_EXT)
    images = collect(ROOT / "resources" / f"obs-{version}-images", IMAGE_EXT)
    bundle = {"version": version, "themes": themes, "images": images}
    out = ROOT / "app" / f"bundle-obs-{version}.js"
    out.write_text(
        "/* Generated by tools/bundle_themes.py from OBS Studio "
        f"{version} (GPL-2.0-or-later). Do not edit. */\n"
        "window.OTI = window.OTI || {};\n"
        "window.OTI.bundles = window.OTI.bundles || [];\n"
        f"window.OTI.bundles.push({json.dumps(bundle, ensure_ascii=False)});\n",
        encoding="utf-8",
    )
    print(f"{out.relative_to(ROOT)}: {len(themes)} theme files, {len(images)} images")


if __name__ == "__main__":
    main()
